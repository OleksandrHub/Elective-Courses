#!/usr/bin/env python3
"""Build the web app (static site for GitHub Pages) into dist/web/.

The web app reuses the extension's UI and styles:
  extension/app.js (built from src/app/ by build.py), extension/css/, extension/courses.json
plus the web-only files in web/ (index.html, main.js, sw.js, manifest, icons).

import.js — the script loaded by the account-import bookmarklet on dl.tntu.edu.ua —
is assembled from the extension's account readers (extension/content/*.js, the
same code the extension uses) followed by web/import-entry.js.

Usage:
    python3 build_web.py                  # build dist/web/
    python3 -m http.server -d dist/web    # preview at http://localhost:8000
"""
import json
import shutil
from pathlib import Path

import build

ROOT = Path(__file__).resolve().parent
EXT = ROOT / "extension"
WEB = ROOT / "web"
OUT = ROOT / "dist" / "web"
# Account readers, in the same order as in the extension manifest.
IMPORT_PARTS = ["common.js", "mandatory.js", "electives.js", "curriculum.js", "account.js"]


def main():
    version = json.loads((EXT / "manifest.json").read_text())["version"]
    (EXT / "app.js").write_text(build.build())
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    shutil.copytree(EXT / "css", OUT / "css")
    shutil.copytree(WEB / "icons", OUT / "icons")
    for name in ("app.js", "courses.json"):
        shutil.copy2(EXT / name, OUT / name)
    for name in ("index.html", "manifest.webmanifest"):
        shutil.copy2(WEB / name, OUT / name)
    for name in ("LICENSE", "TERMS.md", "PRIVACY.md"):
        shutil.copy2(ROOT / name, OUT / name)
    (OUT / "main.js").write_text((WEB / "main.js").read_text().replace("__VERSION__", version))

    parts = [(EXT / "content" / p).read_text() for p in IMPORT_PARTS] + [(WEB / "import-entry.js").read_text()]
    banner = f"// GENERATED by build_web.py (v{version}): extension/content/{{{','.join(IMPORT_PARTS)}}} + web/import-entry.js\n"
    (OUT / "import.js").write_text(banner + "\n".join(parts))

    precache = ["./", "index.html", "main.js", "app.js", "courses.json", "manifest.webmanifest",
                *sorted(f"css/{p.name}" for p in (OUT / "css").glob("*.css")),
                *sorted(f"icons/{p.name}" for p in (OUT / "icons").glob("*.png"))]
    sw = (WEB / "sw.js").read_text().replace("__VERSION__", version).replace("__PRECACHE__", json.dumps(precache))
    (OUT / "sw.js").write_text(sw)
    (OUT / ".nojekyll").write_text("")      # serve files as-is on GitHub Pages

    size = sum(p.stat().st_size for p in OUT.rglob("*") if p.is_file()) / 1024
    print(f"Built {OUT.relative_to(ROOT)} (v{version}, {size:.0f} KB)")


if __name__ == "__main__":
    main()
