#!/usr/bin/env python3
"""Assemble extension/app.js from the parts in src/app/.

The UI is a single function mount() with shared local state, so the parts cannot
be loaded as separate <script>s: they are pasted into its body in filename order.
  00-helpers.js  - constants, typedefs and helpers outside mount() (inside the IIFE)
  10-...99-*.js  - sections of mount()'s body (state, markup, catalog, plan, report, AI...)

Usage: python3 build.py          - build
       python3 build.py --check  - verify that extension/app.js is up to date
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src" / "app"
OUT = ROOT / "extension" / "app.js"
BANNER = "// GENERATED from src/app/*.js by `python3 build.py`. Do not edit this file - edit the parts in src/app/."
# Lines at column 0 that belong to the file header comment of 00-helpers.js
# (`//` lines and/or a `/** ... */` block); they are placed above `(function () {`.
HEADER_PREFIXES = ("//", "/*", " *")
MOUNT_DOC = [
    "  /**",
    "   * Renders the elective picker into `root` and wires up all interaction.",
    "   * All UI sections (src/app/10-...99-*.js) share this function's local state.",
    "   * @param {HTMLElement} root Container element; its contents are replaced.",
    "   * @param {CatalogData} D Scraped course catalog.",
    "   * @param {AppEnv} [env] Host environment (extension hooks); empty for the standalone page.",
    "   */",
]


def build():
    parts = sorted(SRC.glob("*.js"))
    helpers, body = parts[0], parts[1:]
    assert helpers.name.startswith("00-"), "the first part must be 00-helpers.js"
    head = helpers.read_text().rstrip("\n").split("\n")
    n_doc = next(i for i, l in enumerate(head) if not l.startswith(HEADER_PREFIXES))
    lines = [BANNER, *head[:n_doc], "(function () {", *head[n_doc:], "", *MOUNT_DOC, "  function mount(root, D, env = {}) {"]
    for i, p in enumerate(body):
        chunk = p.read_text().rstrip("\n").split("\n")
        if i:
            lines.append("")                      # blank line between parts
        lines += chunk
    lines += ["  }", "", "  window.ElectivesApp = { mount };", "})();", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    out = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == out
        print("extension/app.js is up to date" if ok else "extension/app.js is stale - run python3 build.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(out)
    print(f"Built {OUT.relative_to(ROOT)} from {len(list(SRC.glob('*.js')))} parts")
